-- Criacao das tabelas do DemandaTrack no Oracle.
-- Rodar conectado como o usuario da aplicacao (ver README), antes do seed.sql.
--
-- Regras do Documento de Visao que o proprio banco garante:
--   - tipo, prioridade, status e perfil so aceitam os valores previstos (CHECK);
--   - toda demanda nasce com o status 'Aberta' (DEFAULT);
--   - data de criacao e de atualizacao preenchidas pelo banco (DEFAULT SYSTIMESTAMP);
--   - o responsavel pode ficar em branco (coluna aceita NULL);
--   - nenhuma chave estrangeira usa ON DELETE CASCADE: nao ha exclusao fisica,
--     demanda desnecessaria recebe o status 'Cancelada' e o historico permanece.

SET DEFINE OFF

-- Apaga as tabelas de uma execucao anterior, para o script poder ser rodado de novo.
-- (O Oracle 21c nao tem DROP TABLE IF EXISTS, por isso o bloco PL/SQL.)
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
            WHERE table_name IN ('HISTORICO', 'COMENTARIO', 'DEMANDA', 'USUARIO_PROJETO', 'PROJETO', 'USUARIO')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- Usuarios dos tres perfis. A senha guarda o hash (sal:hash), nunca o texto puro.
CREATE TABLE usuario (
  id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nome   VARCHAR2(100 CHAR) NOT NULL,
  email  VARCHAR2(150 CHAR) NOT NULL UNIQUE,
  senha  VARCHAR2(255) NOT NULL,
  perfil VARCHAR2(20 CHAR) NOT NULL
         CHECK (perfil IN ('Administrador', 'Líder de Projeto', 'Membro da Equipe'))
);

CREATE TABLE projeto (
  id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nome      VARCHAR2(100 CHAR) NOT NULL,
  descricao VARCHAR2(500 CHAR)
);

-- Vinculo N:N entre usuarios e projetos. Lider e Membro so enxergam os seus;
-- o Administrador enxerga todos e por isso nao precisa de linhas aqui.
CREATE TABLE usuario_projeto (
  usuario_id NUMBER NOT NULL REFERENCES usuario (id),
  projeto_id NUMBER NOT NULL REFERENCES projeto (id),
  PRIMARY KEY (usuario_id, projeto_id)
);

-- Entidade principal do sistema (item 2.2 do Documento de Visao).
CREATE TABLE demanda (
  id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  titulo           VARCHAR2(150 CHAR) NOT NULL,
  descricao        VARCHAR2(2000 CHAR) NOT NULL,
  tipo             VARCHAR2(20 CHAR) NOT NULL
                   CHECK (tipo IN ('Tarefa', 'Defeito', 'Melhoria', 'Documentação')),
  prioridade       VARCHAR2(20 CHAR) NOT NULL
                   CHECK (prioridade IN ('Crítica', 'Alta', 'Média', 'Baixa')),
  status           VARCHAR2(20 CHAR) DEFAULT 'Aberta' NOT NULL
                   CHECK (status IN ('Aberta', 'Em andamento', 'Em revisão', 'Concluída', 'Cancelada')),
  projeto_id       NUMBER NOT NULL REFERENCES projeto (id),
  responsavel_id   NUMBER REFERENCES usuario (id),
  data_criacao     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  data_atualizacao TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  prazo            DATE
);

-- Comentario sempre ligado a uma demanda e a um usuario, com data e hora (item 2.2.6).
CREATE TABLE comentario (
  id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  demanda_id NUMBER NOT NULL REFERENCES demanda (id),
  usuario_id NUMBER NOT NULL REFERENCES usuario (id),
  texto      VARCHAR2(2000 CHAR) NOT NULL,
  data_hora  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- Historico de alteracoes (item 2.2.7). A descricao e a frase do que mudou,
-- ex.: "alterou o status da demanda de Aberta para Em andamento."
CREATE TABLE historico (
  id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  demanda_id NUMBER NOT NULL REFERENCES demanda (id),
  usuario_id NUMBER NOT NULL REFERENCES usuario (id),
  descricao  VARCHAR2(500 CHAR) NOT NULL,
  data_hora  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
